#!/usr/bin/env python3
"""Pick the newest GoldHEN .bin in payloads/ and regenerate the pointer + cache manifest.

Usage:  python3 tools/update_payload.py
Just paste a new goldhen_vX.YbZ.W.bin into payloads/ and run this script.
"""

import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAYLOAD_DIR = os.path.join(ROOT, "payloads")
PATTERN = re.compile(r"^goldhen_v(\d+)\.(\d+)b(\d+)\.(\d+)\.bin$")

CORE_FILES = [
    "./index.html",
    "./run.html",
    "./style.css",
    "./app.js",
    "./run.js",
    "./manifest.appcache",
    "./payloads/current.js",
    "./src/wobkot/main.js",
    "./src/wobkot/misc.js",
    "./src/wobkot/userland.js",
    "./src/wobkot/kernel.js",
    "./src/wobkot/lapse.js",
    "./src/wobkot/thread.js",
    "./src/wobkot/worker.js",
    "./src/wobkot/ps4/impl.js",
    "./src/wobkot/LICENSE.txt",
]


def find_latest_payload():
    candidates = []
    for name in os.listdir(PAYLOAD_DIR):
        match = PATTERN.match(name)
        if match and os.path.isfile(os.path.join(PAYLOAD_DIR, name)):
            candidates.append((tuple(int(part) for part in match.groups()), name))

    if not candidates:
        print("No goldhen_v*.bin files found in payloads/", file=sys.stderr)
        return None

    candidates.sort()
    return candidates[-1][1]


def write_pointer(name):
    path = os.path.join(PAYLOAD_DIR, "current.js")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("/* Generated by tools/update_payload.py — do not edit by hand. */\n")
        handle.write('window.LATEST_GOLDHEN = "%s";\n' % name)


def write_manifest(name):
    body = ["CACHE:"] + CORE_FILES + ["./payloads/" + name, "", "NETWORK:", "*"]
    digest = hashlib.sha256("\n".join(body).encode("utf-8")).hexdigest()[:12]

    lines = [
        "CACHE MANIFEST",
        "# payload set: %s" % digest,
        "",
    ] + body

    path = os.path.join(ROOT, "manifest.appcache")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    name = find_latest_payload()
    if not name:
        return 1

    write_pointer(name)
    write_manifest(name)
    print("Active GoldHEN payload: " + name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
